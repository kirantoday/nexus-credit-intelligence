"""Generates the Document Intelligence evaluation corpus's synthetic PDF
fixtures (Milestone 10C). Run once (`python -m eval.document_intelligence.
generate_fixtures` from `backend/`) to (re)create the checked-in fixture
files under `eval/document_intelligence/fixtures/`.

Every fixture is entirely synthetic/original content generated by this
script, never a real production or copyrighted document — per the
milestone brief's explicit instruction not to commit confidential/
copyrighted material, and consistent with every other synthetic-data
convention already established in this codebase (`SYNTHETIC_DEMO_DATA`).
Headings use real font-size differences and tables use real ruling lines
(both live-verified against the installed `pymupdf4llm` 1.28.x before
`corpus_manifest.yaml`'s expectations were written) — a visually-aligned-
text-only "table" would not actually produce Markdown pipe-table syntax,
so every table fixture is drawn with real grid lines.
"""

from __future__ import annotations

from pathlib import Path

import pymupdf as fitz

FIXTURES_DIR = Path(__file__).parent / "fixtures"


def _add_heading(page: fitz.Page, text: str, *, y: float, size: float) -> float:
    page.insert_text((72, y), text, fontsize=size, fontname="helv")
    return y + size + 10


def _add_paragraph(page: fitz.Page, lines: list[str], *, y: float, size: float = 10) -> float:
    for line in lines:
        page.insert_text((72, y), line, fontsize=size, fontname="helv")
        y += size + 5
    return y + 10


def _add_table(
    page: fitz.Page, rows: list[list[str]], *, y: float, col_widths: list[float]
) -> float:
    col_x = [72.0]
    for w in col_widths:
        col_x.append(col_x[-1] + w)
    row_y = [y + i * 25 for i in range(len(rows) + 1)]
    for x in col_x:
        page.draw_line((x, row_y[0]), (x, row_y[-1]))
    for row_line in row_y:
        page.draw_line((col_x[0], row_line), (col_x[-1], row_line))
    for ri, row in enumerate(rows):
        for ci, cell in enumerate(row):
            page.insert_text((col_x[ci] + 4, row_y[ri] + 17), cell, fontsize=9, fontname="helv")
    return row_y[-1] + 20


def generate_credit_agreement_excerpt() -> Path:
    doc = fitz.open()
    page = doc.new_page()
    y = _add_heading(page, "CREDIT AGREEMENT", y=60, size=20)
    y = _add_heading(page, "ARTICLE VI", y=y, size=16)
    y = _add_heading(page, "Financial Covenants", y=y, size=16)
    y = _add_heading(page, "Section 6.11 Maximum First Lien Leverage Ratio", y=y, size=12)
    y = _add_paragraph(
        page,
        [
            "The Borrower shall not permit the First Lien Leverage Ratio as of the",
            "last day of any Test Period to exceed 4.50 to 1.00, tested quarterly",
            "commencing with the fiscal quarter ending March 31, 2027.",
        ],
        y=y,
    )
    y = _add_heading(page, "Section 6.12 Minimum Interest Coverage Ratio", y=y, size=12)
    _add_paragraph(
        page,
        [
            "The Borrower shall not permit the Interest Coverage Ratio to be less",
            "than 3.00 to 1.00 as of the last day of any Test Period.",
        ],
        y=y,
    )

    page2 = doc.new_page()
    y2 = _add_heading(page2, "ARTICLE VII", y=60, size=16)
    y2 = _add_heading(page2, "Negative Covenants", y=y2, size=16)
    y2 = _add_heading(page2, "Section 7.01 Restricted Payments", y=y2, size=12)
    _add_paragraph(
        page2,
        [
            "The Borrower shall not, and shall not permit any Restricted Subsidiary",
            "to, declare or make any Restricted Payment, except as permitted under",
            "the Available Amount basket described in Section 7.01(b).",
        ],
        y=y2,
    )

    path = FIXTURES_DIR / "credit_agreement_excerpt.pdf"
    doc.save(str(path))
    return path


