def generate_scanned_like_blank_page() -> Path:
    """A near-text-free page (a single tiny stray mark) — the fixture
    `detect_needs_ocr` must flag positive, exercised directly in
    `tests/unit/test_extraction_validation.py` against a real
    `ExtractionResult`, not re-parsed from this PDF at test time (the
    fixture exists for the eval runner's own end-to-end pass)."""
    doc = fitz.open()
    page = doc.new_page()
    page.insert_text((72, 72), ".", fontsize=6, fontname="helv")
    path = FIXTURES_DIR / "scanned_like_blank_page.pdf"
    doc.save(str(path))
    return path


